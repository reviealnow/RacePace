export type TranslationKey = keyof typeof english;
export function translate(language: Language, text: TranslationKey): string {
  return language === 'en' ? english[text] : text;
}
export function checkpointName(name: string, language: Language): string {
  return name === '終點' ? translate(language, '終點') : name;
}
export function historyLabel(entry: string, language: Language): string {
  if (language === 'zh') return entry;
  return entry.replaceAll('還原原始設定', english['還原原始設定']).replaceAll('手動調整', english['手動調整']).replaceAll('起跑', english['起跑']).replaceAll('關門', english['關門']).replaceAll('、', ', ');
}
